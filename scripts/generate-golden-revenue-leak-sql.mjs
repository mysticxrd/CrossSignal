import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { buildGoldenEvents, contentHash, detectRevenueLeak, GOLDEN_SCENARIO, sha256 } from "../db/revenue-leak.mjs";

const outputPath = fileURLToPath(new URL("../supabase/scenarios/golden_revenue_leak.sql", import.meta.url));
const scenario = GOLDEN_SCENARIO;
const result = detectRevenueLeak(scenario, buildGoldenEvents(scenario));
const ownerA = `sha256:${sha256("phase1-golden-owner-a")}`;
const ownerB = `sha256:${sha256("phase1-golden-owner-b")}`;
const quote = (value) => `'${String(value).replaceAll("'", "''")}'`;
const j = (value) => `${quote(JSON.stringify(value))}::jsonb`;
const md5 = (value) => createHash("md5").update(value).digest("hex");
const checksum = (rows) => md5(rows.join("|"));
const eventChecksum = checksum(result.events
  .map((event) => `${event.id}:${contentHash(event)}`).sort());
const evidenceChecksum = checksum(result.evidence
  .map((item) => `${item.id}:${contentHash(item)}`).sort());
const refs = result.evidence.flatMap((item) => item.eventIds.map((eventId) => ({ evidenceId: item.id, eventId })));
const refChecksum = checksum(refs.map((item) => `${item.evidenceId}:${item.eventId}`).sort());
const rows = result.events.map((event) => `  (${[
  event.workspaceId, event.id, event.scenarioId, "FIXTURE", event.source,
  event.window, event.segment, event.observedDay,
].map(quote).join(", ")}, ${event.starts}, ${event.completed}, ${event.captures}, ${event.revenueCents}, ${quote(contentHash(event))})`);
const evidenceRows = result.evidence.map((item) => `  (${[
  item.workspaceId, item.id, item.caseId, item.source, item.relation,
  item.claim, item.truthMode, contentHash(item),
].map(quote).join(", ")})`);
const refRows = refs.map((item) => `  (${[scenario.workspaceId, item.evidenceId, item.eventId].map(quote).join(", ")})`);

const sql = `-- Generated by scripts/generate-golden-revenue-leak-sql.mjs. TEST fixture only.
-- Re-running this transaction inserts only missing synthetic rows. It never
-- deletes or overwrites a previously recorded event, Case, signal, or citation.
begin;
set constraints all deferred;

insert into cfr_app.workspaces (id, name, slug, owner_user_id) values
  ('phase1-golden-a', 'Phase 1 golden fixture A', 'phase1-golden-a', ${quote(ownerA)}),
  ('phase1-golden-b', 'Phase 1 isolation fixture B', 'phase1-golden-b', ${quote(ownerB)})
on conflict do nothing;
insert into cfr_app.workspace_members (workspace_id, user_id, role) values
  ('phase1-golden-a', ${quote(ownerA)}, 'owner'),
  ('phase1-golden-b', ${quote(ownerB)}, 'owner')
on conflict do nothing;

insert into cfr_app.case_recorded_events
  (workspace_id, id, scenario_id, truth_mode, source, window_key, segment,
   observed_day, starts, completed, captures, revenue_cents, content_hash)
values
${rows.join(",\n")}
on conflict do nothing;

insert into cfr_app.detected_cases
  (workspace_id, id, scenario_id, scenario_version, scenario_hash,
   title, status, truth_mode, content_hash, created_at)
values (${quote(scenario.workspaceId)}, ${quote(result.caseRecord.id)},
  ${quote(scenario.id)}, ${scenario.version}, ${quote(contentHash(scenario))},
  ${quote(result.caseRecord.title)}, ${quote(result.caseRecord.status)},
  'FIXTURE', ${quote(contentHash(result.caseRecord))}, '2026-09-23T00:00:00Z')
on conflict do nothing;

insert into cfr_app.case_signals
  (workspace_id, id, case_id, kind, method_version, detected, metrics_json, content_hash, created_at)
values (${quote(scenario.workspaceId)}, ${quote(result.signal.id)}, ${quote(result.signal.caseId)},
  ${quote(result.signal.kind)}, ${quote(result.signal.methodVersion)}, ${result.signal.detected},
  ${j(result.signal.metrics)}, ${quote(contentHash(result.signal))}, '2026-09-23T00:00:00Z')
on conflict do nothing;

insert into cfr_app.case_evidence
  (workspace_id, id, case_id, source, relation, claim, truth_mode, content_hash)
values
${evidenceRows.join(",\n")}
on conflict do nothing;

insert into cfr_app.case_evidence_event_refs (workspace_id, evidence_id, event_id)
values
${refRows.join(",\n")}
on conflict do nothing;

do $$
begin
  if not exists (select 1 from cfr_app.workspaces where id = 'phase1-golden-a' and owner_user_id = ${quote(ownerA)})
    or not exists (select 1 from cfr_app.workspaces where id = 'phase1-golden-b' and owner_user_id = ${quote(ownerB)})
    or not exists (select 1 from cfr_app.workspace_members where workspace_id = 'phase1-golden-a' and user_id = ${quote(ownerA)} and role = 'owner')
    or not exists (select 1 from cfr_app.workspace_members where workspace_id = 'phase1-golden-b' and user_id = ${quote(ownerB)} and role = 'owner')
  then raise exception 'golden workspace binding mismatch'; end if;
  if (select count(*) from cfr_app.case_recorded_events
      where workspace_id = ${quote(scenario.workspaceId)} and scenario_id = ${quote(scenario.id)}) <> ${result.events.length}
    or (select md5(string_agg(id || ':' || content_hash, '|' order by id))
      from cfr_app.case_recorded_events where workspace_id = ${quote(scenario.workspaceId)}
        and scenario_id = ${quote(scenario.id)}) <> ${quote(eventChecksum)}
  then raise exception 'golden event set differs from source contract'; end if;
  if not exists (select 1 from cfr_app.detected_cases where workspace_id = ${quote(scenario.workspaceId)}
      and id = ${quote(result.caseRecord.id)} and scenario_hash = ${quote(contentHash(scenario))}
      and content_hash = ${quote(contentHash(result.caseRecord))})
    or not exists (select 1 from cfr_app.case_signals where workspace_id = ${quote(scenario.workspaceId)}
      and id = ${quote(result.signal.id)} and content_hash = ${quote(contentHash(result.signal))})
  then raise exception 'golden Case or signal differs from detection contract'; end if;
  if (select count(*) from cfr_app.case_evidence where workspace_id = ${quote(scenario.workspaceId)}
      and case_id = ${quote(result.caseRecord.id)}) <> ${result.evidence.length}
    or (select md5(string_agg(id || ':' || content_hash, '|' order by id))
      from cfr_app.case_evidence where workspace_id = ${quote(scenario.workspaceId)}
        and case_id = ${quote(result.caseRecord.id)}) <> ${quote(evidenceChecksum)}
  then raise exception 'golden evidence differs from detection contract'; end if;
  if (select count(*) from cfr_app.case_evidence_event_refs where workspace_id = ${quote(scenario.workspaceId)}) <> ${refs.length}
    or (select md5(string_agg(evidence_id || ':' || event_id, '|' order by evidence_id, event_id))
      from cfr_app.case_evidence_event_refs where workspace_id = ${quote(scenario.workspaceId)}) <> ${quote(refChecksum)}
  then raise exception 'golden evidence references differ from recorded events'; end if;
end $$;

commit;
`;

if (process.argv.includes("--check")) {
  if (readFileSync(outputPath, "utf8") !== sql) throw new Error("Golden SQL is stale; regenerate it.");
  process.stdout.write("Golden SQL matches deterministic source.\n");
} else {
  writeFileSync(outputPath, sql, "utf8");
  process.stdout.write(`${outputPath}\n`);
}
